const q = (s) => `'${s.replace(/'/g, "''")}'`;
let sql = `-- Generated by docs/phase5/acronyms.mjs. Spells out acronyms on company cards (Phase 5).\nbegin;\n`;
for (const [t, from, to] of edits) {
  const f = q(from), n = q(to);
  sql += `do $$ declare c int; begin
  with s as (update public.stocks set
      mission_story = replace(mission_story, ${f}, ${n}),
      proof = replace(proof, ${f}, ${n}),
      things_to_know = (select array_agg(replace(e, ${f}, ${n}) order by i) from unnest(things_to_know) with ordinality u(e, i))
    where ticker = ${q(t)} and (mission_story like '%' || ${f} || '%' or proof like '%' || ${f} || '%' or array_to_string(things_to_know, '|') like '%' || ${f} || '%') returning 1),
  m as (update public.stock_missions set why_line = replace(why_line, ${f}, ${n})
    where ticker = ${q(t)} and why_line like '%' || ${f} || '%' returning 1)
  select (select count(*) from s) + (select count(*) from m) into c;
  if c <> 1 then raise exception '${t}: expected 1 row for %, got %', ${f}, c; end if;
end $$;\n`;
}
sql += `do $$ declare c int; begin
  update public.causes set tagline = 'Solar, wind, batteries, the grid and electric cars' where id = 'clean_energy' and tagline = 'Solar, wind, batteries, the grid and EVs';
  get diagnostics c = row_count; if c <> 1 then raise exception 'clean_energy tagline: got %', c; end if;
end $$;\n`;
fs.writeFileSync('docs/phase5/acronyms.sql', sql + 'commit;\n');

