#!/usr/bin/env node
// Builds the launch-universe migration and review document from supabase/seed/launch-universe.json.
// Usage: node scripts/build-launch-seed.mjs [migration-file-name]
//   writes supabase/migrations/<name> (default: 20261019190000_launch_universe.sql)
//   writes supabase/seed/launch-universe-review.md
// The JSON is the source of truth: re-running and re-applying the migration syncs the database to it
// (missions, flags and feed membership not in the JSON are removed).
import { readFileSync, writeFileSync } from 'node:fs';

const CAUSES = {
  beat_cancer: 'Beat cancer & disease',
  live_healthier: 'Live longer & healthier',
  clean_energy: 'Clean energy & climate',
  keeping_safe: 'Keeping people safe',
};
const EXPOSURES = ['core', 'partial', 'peripheral'];
const DEALBREAKERS = ['tobacco', 'weapons', 'fossil_fuels', 'gambling', 'animal_testing', 'factory_farming'];
const SECTORS = ['technology', 'healthcare', 'finance', 'energy', 'consumer', 'utilities', 'industrials'];
const RISKS = ['low', 'medium', 'high'];

const { companies } = JSON.parse(readFileSync('supabase/seed/launch-universe.json', 'utf8'));
const migrationName = process.argv[2] ?? '20261019190000_launch_universe.sql';

// --- validation ---
const errors = [];
const seen = new Set();
for (const c of companies) {
  const where = c.ticker ?? '(missing ticker)';
  if (!/^[A-Z.]{1,6}$/.test(c.ticker ?? '')) errors.push(`${where}: bad ticker`);
  if (seen.has(c.ticker)) errors.push(`${where}: duplicate`);
  seen.add(c.ticker);
  if (!c.company_name) errors.push(`${where}: missing company_name`);
  if (!SECTORS.includes(c.sector)) errors.push(`${where}: bad sector ${c.sector}`);
  if (!RISKS.includes(c.risk_level)) errors.push(`${where}: bad risk_level ${c.risk_level}`);
  for (const field of ['mission_story', 'proof']) if (!c[field]?.trim()) errors.push(`${where}: missing ${field}`);
  if (!Array.isArray(c.things_to_know) || c.things_to_know.length === 0) errors.push(`${where}: missing things_to_know`);
  if (!Array.isArray(c.missions) || c.missions.length === 0) errors.push(`${where}: no missions`);
  for (const m of c.missions ?? []) {
    if (!CAUSES[m.cause]) errors.push(`${where}: unknown cause ${m.cause}`);
    if (!EXPOSURES.includes(m.exposure)) errors.push(`${where}: bad exposure ${m.exposure}`);
    if (!m.evidence?.trim() || !m.why_line?.trim()) errors.push(`${where}: mission ${m.cause} needs evidence and why_line`);
  }
  for (const f of c.flags ?? []) {
    if (!DEALBREAKERS.includes(f.dealbreaker)) errors.push(`${where}: unknown dealbreaker ${f.dealbreaker}`);
    if (!f.evidence?.trim()) errors.push(`${where}: flag ${f.dealbreaker} needs evidence`);
  }
  if (c.new && !c.profile?.description) errors.push(`${where}: new company needs profile.description`);
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

// SEC EDGAR filings page for the company (annual report type where known)
const sourceUrl = (c) =>
  `https://www.sec.gov/cgi-bin/browse-edgar?action=getcompany&CIK=${c.ticker}${c.filing_type ? `&type=${c.filing_type}` : ''}&dateb=&owner=include&count=40`;

// --- SQL ---
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `ARRAY[${xs.map(q).join(', ')}]::text[]`;
const tickers = companies.map(c => q(c.ticker)).join(', ');

const sql = [];
sql.push(`-- Release 1 launch universe, generated by scripts/build-launch-seed.mjs from
-- supabase/seed/launch-universe.json. Edit the JSON and regenerate rather than editing this file.
-- ${companies.length} companies (${companies.filter(c => c.new).length} new).
-- Content was drafted by Claude (tagged_by = 'ai'); reviewed_at is set once a company is
-- marked "reviewed": true in the JSON.

-- A sector for safety and electrical-equipment companies (not shown by older builds' views)
ALTER TABLE public.stocks DROP CONSTRAINT IF EXISTS stocks_sector_check;
ALTER TABLE public.stocks ADD CONSTRAINT stocks_sector_check
  CHECK (sector IN (${SECTORS.map(q).join(', ')}));

-- New companies. updated_at in the past puts them first in line for the price updater.`);
for (const c of companies.filter(c => c.new)) {
  const p = c.profile;
  sql.push(`INSERT INTO public.stocks (ticker, company_name, sector, risk_level, description, city, state, country, in_feed, updated_at, last_updated)
VALUES (${q(c.ticker)}, ${q(c.company_name)}, ${q(c.sector)}, ${q(c.risk_level)}, ${q(p.description)}, ${q(p.city)}, ${q(p.state)}, ${q(p.country ?? 'US')}, true, '2000-01-01', '2000-01-01')
ON CONFLICT (ticker) DO UPDATE SET company_name = EXCLUDED.company_name, sector = EXCLUDED.sector, risk_level = EXCLUDED.risk_level,
  description = EXCLUDED.description, city = EXCLUDED.city, state = EXCLUDED.state, country = EXCLUDED.country, in_feed = true;`);
}

sql.push(`\n-- Mission story, proof and things to know for every launch company`);
for (const c of companies) {
  sql.push(`UPDATE public.stocks SET mission_story = ${q(c.mission_story)}, proof = ${q(c.proof)}, proof_source_url = ${q(sourceUrl(c))},
  things_to_know = ${arr(c.things_to_know)}, in_feed = true WHERE ticker = ${q(c.ticker)};`);
}
sql.push(`UPDATE public.stocks SET in_feed = false WHERE in_feed AND ticker NOT IN (${tickers});`);

sql.push(`\n-- Cause tags (missions)`);
const missionKeys = [];
for (const c of companies) {
  for (const m of c.missions) {
    missionKeys.push(`(${q(c.ticker)}, ${q(m.cause)})`);
    sql.push(`INSERT INTO public.stock_missions (ticker, cause, exposure, evidence, source_url, why_line, status, tagged_by, reviewed_at)
VALUES (${q(c.ticker)}, ${q(m.cause)}, ${q(m.exposure)}, ${q(m.evidence)}, ${q(sourceUrl(c))}, ${q(m.why_line)}, 'approved', 'ai', ${c.reviewed ? 'now()' : 'NULL'})
ON CONFLICT (ticker, cause) DO UPDATE SET exposure = EXCLUDED.exposure, evidence = EXCLUDED.evidence, source_url = EXCLUDED.source_url,
  why_line = EXCLUDED.why_line, status = 'approved', reviewed_at = COALESCE(EXCLUDED.reviewed_at, public.stock_missions.reviewed_at),
  version = public.stock_missions.version + 1, updated_at = now();`);
  }
}
sql.push(`DELETE FROM public.stock_missions WHERE (ticker, cause) NOT IN (${missionKeys.join(', ')});`);

sql.push(`\n-- Dealbreaker flags`);
const flagKeys = [];
for (const c of companies) {
  for (const f of c.flags ?? []) {
    flagKeys.push(`(${q(c.ticker)}, ${q(f.dealbreaker)})`);
    sql.push(`INSERT INTO public.stock_flags (ticker, dealbreaker, evidence, source_url)
VALUES (${q(c.ticker)}, ${q(f.dealbreaker)}, ${q(f.evidence)}, ${q(sourceUrl(c))})
ON CONFLICT (ticker, dealbreaker) DO UPDATE SET evidence = EXCLUDED.evidence, source_url = EXCLUDED.source_url;`);
  }
}
sql.push(flagKeys.length
  ? `DELETE FROM public.stock_flags WHERE (ticker, dealbreaker) NOT IN (${flagKeys.join(', ')});`
  : `DELETE FROM public.stock_flags;`);

writeFileSync(`supabase/migrations/${migrationName}`, sql.join('\n') + '\n');

// --- review document ---
const md = [];
md.push(`# Launch universe review (Release 1)

Generated from \`supabase/seed/launch-universe.json\` by \`node scripts/build-launch-seed.mjs\`.
**Drafted by Claude from general knowledge: verify facts and numbers against the source link.**
To approve a company, set \`"reviewed": true\` for it in the JSON (or tell Claude which ones to change).

| Cause | Companies | Reviewed |
|---|---|---|
${Object.entries(CAUSES).map(([id, label]) => {
  const inCause = companies.filter(c => c.missions.some(m => m.cause === id && m.exposure !== 'peripheral'));
  return `| ${label} | ${inCause.length} | ${inCause.filter(c => c.reviewed).length} |`;
}).join('\n')}
`);
for (const [id, label] of Object.entries(CAUSES)) {
  md.push(`\n## ${label}\n`);
  companies.filter(c => c.missions[0].cause === id).forEach((c, i) => {
    const lines = [
      `- **Story:** ${c.mission_story}`,
      `- **Proof:** ${c.proof}`,
      `- **Things to know:** ${c.things_to_know.join(' ')}`,
      ...c.missions.map(m => `- **${CAUSES[m.cause]} (${m.exposure}):** ${m.why_line}  \n  *Evidence:* ${m.evidence}`),
      ...(c.flags ?? []).map(f => `- **Flag (${f.dealbreaker.replace('_', ' ')}):** ${f.evidence}`),
      ...(c.new ? [`- **Profile:** ${c.profile.description} (${[c.profile.city, c.profile.state, c.profile.country !== 'US' ? c.profile.country : null].filter(Boolean).join(', ')}) · sector ${c.sector} · risk ${c.risk_level}`] : []),
      `- [SEC filings](${sourceUrl(c)})`,
    ];
    md.push(`### ${i + 1}. ${c.ticker}: ${c.company_name}${c.new ? ' (new)' : ''}${c.reviewed ? ' ✅' : ''}\n\n${lines.join('\n')}\n`);
  });
}
writeFileSync('supabase/seed/launch-universe-review.md', md.join('\n'));

const byCause = Object.keys(CAUSES).map(id => `${id}: ${companies.filter(c => c.missions.some(m => m.cause === id && m.exposure !== 'peripheral')).length}`);
console.log(`OK: ${companies.length} companies (${byCause.join(', ')}), ${missionKeys.length} missions, ${flagKeys.length} flags`);
console.log(`Wrote supabase/migrations/${migrationName} and supabase/seed/launch-universe-review.md`);
