#!/usr/bin/env node
// Writes the app's color tokens (src/styles/tokens.css) from the tested palette in
// docs/phase0/tokens.json (made by scripts/palette-check.mjs from docs/phase0/palettes.json).
// Each token is an "R G B" triplet so Tailwind's opacity modifiers work (rgb(var(--x) / 0.5)),
// and so it renders on iOS 15.0 web views, which don't support oklch() (added in iOS 15.4).
// The OKLCH source of every token is kept in a comment next to it.
// Usage: node scripts/build-tokens.mjs [direction=daybreak]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const id = process.argv[2] ?? 'daybreak';
const tk = JSON.parse(readFileSync('docs/phase0/tokens.json', 'utf8'))[id];
if (!tk) throw new Error(`unknown direction ${id}`);
const rgb = (h) => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16)).join(' ');
const line = (name, t) => `  --${name}: ${rgb(t.hex)}; /* ${t.hex} ${t.oklch} */`;

const out = [`/* Generated by scripts/build-tokens.mjs from docs/phase0/tokens.json (${tk.name}).
   Edit docs/phase0/palettes.json, run node scripts/palette-check.mjs (contrast and color-blindness
   tests), then node scripts/build-tokens.mjs. Do not edit by hand. */
:root {`];
out.push('  /* Surfaces and text */');
for (const k of ['base', 'surface', 'surface2', 'border', 'text', 'text2', 'text3', 'text4', 'highlight']) if (tk[k]) out.push(line(k, tk[k]));
const TONES = ['deep', 'ink', 'bright', 'vivid', 'soft', 'border', 'tint'];
out.push('  /* Families: deep = text and icons, ink = text on soft, bright = graphics, vivid = bold bands,\n     soft = badges, border, tint = boxes */');
for (const fam of ['primary', 'positive', 'info', 'caution', 'premium', 'donation']) {
  for (const tone of TONES) out.push(line(`${fam}-${tone}`, tk[fam][tone]));
}
out.push('  /* Causes */');
for (const [cause, f] of Object.entries(tk.causes)) for (const tone of TONES) out.push(line(`cause-${cause.replace(/_/g, '-')}-${tone}`, f[tone]));
out.push('}');
mkdirSync('src/styles', { recursive: true });
writeFileSync('src/styles/tokens.css', out.join('\n') + '\n');
console.log(`wrote src/styles/tokens.css (${out.length - 4} tokens, ${tk.name})`);
